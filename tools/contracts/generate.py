"""Generate Python and TypeScript types from every contract (deterministic).

    python -m tools.contracts.generate           # write the generated files
    python -m tools.contracts.generate --check   # fail with CONTRACT_TYPES_STALE if out of date

Python: datamodel-code-generator (Pydantic v2) into the `contracts` distribution.
TypeScript: json-schema-to-typescript (run from `web/`) into `web/src/lib/contracts/`.
Contracts whose name starts with `_` are fixtures: their Python types go to `tests/contracts/`.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from tools.contracts.validate import ContractVersion, contract_versions, load_document
from tools.repository import REPOSITORY_ROOT, identity

WEB = REPOSITORY_ROOT / "web"
WEB_TOOLS = WEB / "node_modules" / ".bin"
MARKER = '"""Generated contract types. Do not edit."""\n'


class GenerationError(RuntimeError):
    """A generator failed; the message carries its standard error."""


def run(command: list[str], cwd: Path | None = None) -> None:
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise GenerationError(f"{' '.join(command[:3])} failed:\n{result.stderr or result.stdout}")


def web_tool(name: str) -> str:
    """A tool from web/node_modules only: never let `npx` download a package by that name."""
    path = WEB_TOOLS / (f"{name}.cmd" if sys.platform == "win32" else name)
    if not path.exists():
        raise GenerationError(
            f"CONTRACT_TOOLING_MISSING: {path.relative_to(REPOSITORY_ROOT)}; run `npm ci` in web/"
        )
    return str(path)


def namespace_contracts() -> Path:
    namespace = str(identity(REPOSITORY_ROOT)["python_namespace"])
    return REPOSITORY_ROOT / "packages" / "contracts" / "src" / namespace / "contracts"


def generated_files_on_disk() -> set[Path]:
    """Every file under the generated roots, except the hand-written ones."""
    python_version = re.compile(r"(__init__|v[1-9][0-9]*)\.py")
    fixture = re.compile(r"[a-z0-9_]+_v[1-9][0-9]*\.py")
    typescript = re.compile(r"v[1-9][0-9]*\.ts")
    found = {p for p in namespace_contracts().glob("*/*.py") if python_version.fullmatch(p.name)}
    found |= {
        p
        for p in (REPOSITORY_ROOT / "tests" / "contracts" / "generated").glob("*.py")
        if fixture.fullmatch(p.name)
    }
    found |= {
        p
        for p in (WEB / "src" / "lib" / "contracts").glob("*/*.ts")
        if typescript.fullmatch(p.name)
    }
    return found


def header(contract: ContractVersion, comment: str) -> str:
    source = contract.document.relative_to(REPOSITORY_ROOT).as_posix()
    return f"{comment} Generated by tools/contracts/generate.py from {source}. Do not edit.\n"


def python_path(contract: ContractVersion) -> Path:
    module = contract.name.lstrip("_").replace("-", "_")
    if contract.name.startswith("_"):
        return (
            REPOSITORY_ROOT
            / "tests"
            / "contracts"
            / "generated"
            / f"{module}_{contract.version}.py"
        )
    return namespace_contracts() / module / f"{contract.version}.py"


def typescript_path(contract: ContractVersion) -> Path:
    return WEB / "src" / "lib" / "contracts" / contract.name / f"{contract.version}.ts"


def python_types(contract: ContractVersion, scratch: Path) -> str:
    output = scratch / "model.py"
    run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(contract.document),
            "--input-file-type",
            "openapi" if contract.is_openapi else "jsonschema",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.14",
            "--use-annotated",
            "--field-constraints",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal",
            "all",
            "--use-double-quotes",
            "--use-schema-description",
            "--use-field-description",
            "--disable-timestamp",
            "--formatters",
            "ruff-format",
        ]
    )
    generated = output.read_text(encoding="utf-8")
    body = generated.split("\n", 2)[2] if generated.startswith("# generated by") else generated
    output.write_text(header(contract, "#") + "\n" + body.lstrip("\n"), encoding="utf-8")
    # Format with the repository's own settings so the committed file is stable under `ruff`.
    configuration = str(REPOSITORY_ROOT / "pyproject.toml")
    # E501: descriptions copied from contracts may exceed the line length (see pyproject.toml).
    for command in (
        ["check", "--fix", "--quiet", "--extend-ignore", "E501"],
        ["format", "--quiet"],
    ):
        run([sys.executable, "-m", "ruff", *command, "--config", configuration, str(output)])
    return output.read_text(encoding="utf-8")


def json_schema_bundle(contract: ContractVersion) -> dict[str, Any]:
    """The contract as one JSON Schema; OpenAPI component schemas become `$defs`."""
    document = load_document(contract)
    if not contract.is_openapi:
        return document
    text = json.dumps(document["components"]["schemas"]).replace(
        "#/components/schemas/", "#/$defs/"
    )
    title = (
        "".join(part.capitalize() for part in contract.name.split("-")) + contract.version.upper()
    )
    return {"title": title, "$defs": json.loads(text)}


def typescript_types(contract: ContractVersion, scratch: Path) -> str:
    bundle = scratch / "schema.json"
    output = scratch / "types.ts"
    bundle.write_text(json.dumps(json_schema_bundle(contract)), encoding="utf-8")
    run(
        [
            web_tool("json2ts"),
            "--input",
            str(bundle),
            "--output",
            str(output),
            "--unreachableDefinitions",
            "--no-bannerComment",
            "--additionalProperties",
            "false",
        ],
        cwd=WEB,
    )
    run(
        [web_tool("prettier"), "--write", str(output), "--config", str(WEB / ".prettierrc")],
        cwd=WEB,
    )
    types = output.read_text(encoding="utf-8")
    if contract.is_openapi:
        # The OpenAPI bundle itself is not a type; drop the open placeholder json2ts emits for it.
        title = json_schema_bundle(contract)["title"]
        types, removed = re.subn(
            rf"export interface {title} \{{\n\t\[k: string\]: unknown;\n\}}\n", "", types
        )
        if removed != 1:
            raise GenerationError(f"json2ts output changed: no placeholder '{title}' to remove")
    return header(contract, "//") + types


def generate_all() -> dict[Path, str]:
    files: dict[Path, str] = {}
    with tempfile.TemporaryDirectory() as directory:
        scratch = Path(directory)
        for contract in contract_versions():
            files[python_path(contract)] = python_types(contract, scratch)
            files[typescript_path(contract)] = typescript_types(contract, scratch)
    return files


def package_markers(files: dict[Path, str]) -> dict[Path, str]:
    """`__init__.py` for each generated contract package under the contracts distribution."""
    root = namespace_contracts()
    return {
        path.parent / "__init__.py": MARKER
        for path in files
        if path.suffix == ".py" and path.parent.parent == root
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail if the committed output differs")
    arguments = parser.parse_args()
    try:
        files = generate_all()
    except GenerationError as error:
        print(error)
        return 1
    files |= package_markers(files)
    stale = [
        path
        for path, text in sorted(files.items())
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
    orphans = sorted(generated_files_on_disk() - set(files))
    if arguments.check:
        for path in [*stale, *orphans]:
            print(f"CONTRACT_TYPES_STALE: {path.relative_to(REPOSITORY_ROOT)}")
        print(f"contracts: {len(stale) + len(orphans)} stale generated file(s)")
        return 1 if stale or orphans else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
        print(f"wrote {path.relative_to(REPOSITORY_ROOT)}")
    for path in orphans:
        path.unlink()
        print(f"removed {path.relative_to(REPOSITORY_ROOT)}")
        if path.parent != namespace_contracts() and not any(path.parent.iterdir()):
            path.parent.rmdir()
    return 0


if __name__ == "__main__":
    sys.exit(main())
