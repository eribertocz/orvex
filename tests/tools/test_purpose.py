"""Every hand-written module states its one purpose (`tools/checks/purpose.py`)."""

from __future__ import annotations

from pathlib import Path

import pytest

from tools.checks import purpose


def _file(root: Path, relative: str, text: str) -> Path:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, "utf-8")
    return root


@pytest.mark.parametrize(
    "relative",
    [
        "packages/store/src/orvex/store/guard.py",
        "tools/checks/thing.py",
        "conformance/runners/runner.py",
    ],
)
def test_a_module_without_a_purpose_fails(tmp_path: Path, relative: str) -> None:
    root = _file(tmp_path, relative, "x = 1\n")
    (finding,) = purpose.findings(root)
    assert finding.path == relative
    assert purpose.main(root) == 1


@pytest.mark.parametrize("text", ['""""""\nx = 1\n', '"""   \n\n"""\nx = 1\n', "# a comment\n"])
def test_an_empty_docstring_or_a_comment_is_not_a_purpose(tmp_path: Path, text: str) -> None:
    root = _file(tmp_path, "packages/store/src/orvex/store/guard.py", text)
    assert len(purpose.findings(root)) == 1


def test_a_stated_purpose_passes(tmp_path: Path) -> None:
    root = _file(
        tmp_path, "packages/store/src/orvex/store/guard.py", '"""The SQL guard."""\nx = 1\n'
    )
    assert purpose.findings(root) == []
    assert purpose.main(root) == 0


def test_generated_modules_and_empty_package_markers_are_exempt(tmp_path: Path) -> None:
    header = "# Generated by tools/contracts/generate.py from contracts/store/v1/schema.json.\n"
    _file(tmp_path, "packages/contracts/src/orvex/contracts/store/v1.py", header + "x = 1\n")
    _file(tmp_path, "packages/store/src/orvex/store/__init__.py", "")
    assert purpose.findings(tmp_path) == []


@pytest.mark.parametrize(
    "relative",
    [
        "packages/store/src/orvex/store/tests/helper.py",  # a `tests` folder inside the roots
        "tools/tests/helper.py",
        "packages/contracts/src/orvex/contracts/hand/v1.py",  # named like a generated module
    ],
)
def test_nothing_else_inside_the_roots_is_exempt(tmp_path: Path, relative: str) -> None:
    root = _file(tmp_path, relative, "x = 1\n")
    assert [finding.path for finding in purpose.findings(root)] == [relative]


def test_a_package_marker_with_code_needs_a_purpose(tmp_path: Path) -> None:
    root = _file(tmp_path, "packages/store/src/orvex/store/__init__.py", "x = 1\n")
    assert len(purpose.findings(root)) == 1


def test_the_repository_states_every_purpose() -> None:
    from tools.repository import REPOSITORY_ROOT

    assert purpose.findings(REPOSITORY_ROOT) == []
